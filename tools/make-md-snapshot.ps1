# Regenerates assets/js/md-snapshot.js from the Master Data prototype HTML (no Node needed).
# Each Master Data module is read from ITS OWN page (the file a user opens for that module), because
# the MD pages are separate copies and their inline seeds can drift. The seed block of each page
# (from "const IC={" up to "const LS_PREFIX") is evaluated in headless Edge and the rows + picklists (O)
# are dumped to JSON. Nothing in Master Data is modified.
# Usage:  powershell -ExecutionPolicy Bypass -File tools\make-md-snapshot.ps1
$ErrorActionPreference = 'Stop'
$build = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$mdDir = (Resolve-Path (Join-Path $build '..\..\Master Data\Combined with P2H, Cost, Location')).Path
$edge = "C:\Program Files (x86)\Microsoft\Edge\Application\msedge.exe"
if (-not (Test-Path $edge)) { $edge = "C:\Program Files\Google\Chrome\Application\chrome.exe" }
# module -> source page
$map = [ordered]@{
  customer='customer'; custrate='customer-rate'; vendor='vendor'; vendrate='vendor-rate'; priority='vendor-priority';
  vehicle='vehicle'; driver='driver'; location='location'; p2h='p2h';
  tc_bbm='trip-cost'; tc_mel='trip-cost'; tc_parkir='trip-cost'; tc_makan='trip-cost'; tc_ferry='trip-cost';
  tc_handling='trip-cost'; tc_tkbm='trip-cost'; tc_asem='trip-cost'; incentive='incentive-cost' }
$files = $map.Values | Select-Object -Unique
$js = New-Object System.Text.StringBuilder
[void]$js.Append("window.__OUT={files:{}};`n")
foreach ($f in $files) {
  $t = [IO.File]::ReadAllText((Join-Path $mdDir "$f.html"))
  $a = $t.IndexOf('const IC={'); $b = $t.IndexOf('const LS_PREFIX')
  if ($a -lt 0 -or $b -lt $a) { throw "Seed block not found in $f.html" }
  $seg = $t.Substring($a, $b - $a).Replace('</script', '<\/script')
  $sv = [regex]::Match($t, 'const SEED_VERSION=(\d+)').Groups[1].Value
  [void]$js.Append("(function(){try{`n$seg`n;var R={};Object.keys(M).forEach(function(k){if(M[k]&&M[k].rows)R[k]=M[k].rows;});window.__OUT.files['$f']={seedVersion:$sv,O:O,rows:R};}catch(e){window.__OUT.files['$f']={error:String(e)};}})();`n")
}
[void]$js.Append("document.getElementById('out').textContent=btoa(unescape(encodeURIComponent(JSON.stringify(window.__OUT))));")
$tmpDir = Join-Path $env:TEMP 'moda-md-snap'; New-Item -ItemType Directory -Force $tmpDir | Out-Null
$page = Join-Path $tmpDir 'extract.html'
[IO.File]::WriteAllText($page, "<!doctype html><html><head><meta charset='utf-8'></head><body><pre id='out'></pre><script>`n" + $js.ToString() + "`n</script></body></html>", (New-Object Text.UTF8Encoding $false))
$prof = Join-Path $tmpDir 'prof'
$ErrorActionPreference = 'Continue'
$domFile = Join-Path $tmpDir 'dom.txt'
$p = Start-Process -FilePath $edge -ArgumentList @('--headless=new','--disable-gpu',"--user-data-dir=`"$prof`"",'--virtual-time-budget=4000','--dump-dom',("`"file:///" + $page.Replace('\','/') + "`"")) -RedirectStandardOutput $domFile -RedirectStandardError (Join-Path $tmpDir 'err.txt') -PassThru -Wait -WindowStyle Hidden
$ErrorActionPreference = 'Stop'
$dom = [IO.File]::ReadAllText($domFile)
$m = [regex]::Match($dom, "<pre id=`"out`">([A-Za-z0-9+/=]+)</pre>")
if (-not $m.Success) { throw "Extraction failed (no output). DOM head: " + $dom.Substring(0, [Math]::Min(400, $dom.Length)) }
$json = [Text.Encoding]::UTF8.GetString([Convert]::FromBase64String($m.Groups[1].Value))
$obj = $json | ConvertFrom-Json
foreach ($f in $files) { if ($obj.files.$f.error) { throw "$f.html: $($obj.files.$f.error)" } }
# assemble: rows of each module from its own page; O merged (vehicle page wins for vehicle picklists)
$sb = New-Object System.Text.StringBuilder
[void]$sb.Append("/* GENERATED by tools/make-md-snapshot.ps1 - do not edit by hand. Source: Grand Design UI/Master Data/Combined with P2H, Cost, Location/*.html`n   Generated " + (Get-Date -Format 'yyyy-MM-dd HH:mm') + ". Each module comes from its own page; O = picklists. */`n")
[void]$sb.Append("window.MD_SNAPSHOT={generatedAt:'" + (Get-Date -Format 'yyyy-MM-ddTHH:mm') + "',seedVersion:" + $obj.files.vehicle.seedVersion + ",source:{")
[void]$sb.Append((($map.Keys | ForEach-Object { "$_" + ":'" + $map[$_] + ".html'" }) -join ','))
[void]$sb.Append("},rows:{`n")
$parts = @()
foreach ($k in $map.Keys) {
  $src = $obj.files.($map[$k]).rows.$k
  if ($null -eq $src) { continue }
  $parts += (" " + $k + ":" + (ConvertTo-Json -InputObject @($src) -Depth 20 -Compress))
}
[void]$sb.Append(($parts -join ",`n"))
[void]$sb.Append("},`nO:")
# O: union of keys, vehicle.html first (newest picklists), then others fill missing keys
$picks = [ordered]@{}
foreach ($f in @('vehicle') + ($files | Where-Object { $_ -ne 'vehicle' })) { $po = $obj.files.$f.O; foreach ($p in $po.PSObject.Properties) { if (-not $picks.Contains($p.Name)) { $picks[$p.Name] = $p.Value } } }
[void]$sb.Append((ConvertTo-Json -InputObject $picks -Depth 10 -Compress))
[void]$sb.Append("};`n")
$out = Join-Path $build 'assets\js\md-snapshot.js'
[IO.File]::WriteAllText($out, $sb.ToString(), (New-Object Text.UTF8Encoding $false))
"Wrote $out (" + (Get-Item $out).Length + " bytes)"
foreach ($k in $map.Keys) { $n = @($obj.files.($map[$k]).rows.$k).Count; "  $k <- $($map[$k]).html : $n rows" }
